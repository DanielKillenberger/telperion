import { createServer } from 'vite';
import { chromium } from 'playwright';
import { writeFile } from 'node:fs/promises';
const output=process.env.GENERATION_OUTPUT;
if(!output) throw Error('GENERATION_OUTPUT required');
const server=await createServer({server:{host:'127.0.0.1',port:0}});
await server.listen();
const url=`http://127.0.0.1:${server.httpServer.address().port}`;
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:false,args:['--no-sandbox','--enable-unsafe-webgpu','--enable-features=Vulkan','--use-angle=vulkan','--disable-vulkan-surface','--ignore-gpu-blocklist']});
const result={date:new Date().toISOString(),browser:browser.version()};
try {
 const page=await browser.newPage({viewport:{width:1280,height:720}});
 await page.route(url+'/',r=>r.fulfill({contentType:'text/html',body:'<canvas style="width:1280px;height:720px"></canvas>'}));
 await page.goto(url);
 result.checks=await page.evaluate(async()=>{
  const {createRenderer}=await import('/src/browser/render.ts');
  const {presetById}=await import('/src/browser/core.ts');
  const {familyJson,presetToParams}=await import('/harness/family.ts');
  const family=JSON.parse(familyJson(presetToParams(presetById('oregon-white-oak'))));
  family.skeleton.attractors=16;
  const text=JSON.stringify(family);
  const renderer=await createRenderer(document.querySelector('canvas'));
  const checks={};
  const assert=(condition,message)=>{if(!condition)throw Error(message);};
  const rejected=async(p,fragment)=>{try{await p;}catch(e){assert(String(e).includes(fragment),String(e));return String(e);}throw Error('expected rejection: '+fragment);};
  const cpu=renderer.setTree(text);
  const gpu=await renderer.setTreeGpu(text);
  assert(gpu.backend==='Gpu','GPU backend');
  assert(gpu.foliageInstances===cpu.foliageInstances && gpu.woodVertices===cpu.woodVertices,'count mismatch');
  assert([...gpu.bounds.min,...gpu.bounds.max].every(Number.isFinite),'finite bounds');
  checks.valid={cpu,gpu};
  checks.invalid=await rejected(renderer.setTreeGpu('{'),'not JSON');
  const fallback=structuredClone(family);fallback.canopy.shortShootSpacing=0.1;
  checks.fallback=await renderer.setTreeGpu(JSON.stringify(fallback));
  assert(checks.fallback.backend==='CpuFallback','fallback backend');
  const first=renderer.setTreeGpu(text);
  checks.overlap=await rejected(renderer.setTreeGpu(text),'busy');
  await first;
  const replacement=structuredClone(family);replacement.skeleton.seed=7;
  const pending=renderer.setTreeGpu(text);
  const submitted=renderer.setTree(JSON.stringify(replacement));
  const before=renderer.hero();renderer.frame();const beforeStats=renderer.stats();
  checks.stale=await rejected(pending,'stale');
  const after=renderer.hero();renderer.frame();const afterStats=renderer.stats();
  assert(JSON.stringify(before)===JSON.stringify(after),'stale result replaced bounds/camera');
  assert(JSON.stringify(beforeStats)===JSON.stringify(afterStats),'stale result replaced rendered geometry');
  checks.replacement={submitted,before,after,beforeStats,afterStats};
  const disposing=renderer.setTreeGpu(text);
  await Promise.resolve();
  renderer.dispose();
  checks.disposal=await rejected(disposing,'disposed');
  checks.afterDisposal=await rejected(renderer.setTreeGpu(text),'disposed');
  checks.liveDevices=window.telperionLiveDevices;
  assert(checks.liveDevices===0,'disposed live device count');
  return checks;
 });
 result.passed=true;
} catch(error) {result.error=String(error);throw error;}
finally{await writeFile(output,JSON.stringify(result,null,2)+'\n');await browser.close();await server.close();}
