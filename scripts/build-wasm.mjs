import { execFileSync } from 'node:child_process';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const root = new URL('../', import.meta.url);
// Cargo builds into CARGO_TARGET_DIR when set; the binding is read from there,
// never from a stale default target (fn-256 FRICTION.md).
const target = pathToFileURL(resolve(fileURLToPath(root), process.env.CARGO_TARGET_DIR ?? 'target') + '/');
execFileSync('cargo', ['build', '--release', '--target', 'wasm32-unknown-unknown', '-p', 'telperion-wasm'], { cwd: root, stdio: 'inherit', timeout: 600_000 });
const source = new URL('wasm32-unknown-unknown/release/telperion_wasm.wasm', target);
const { instance } = await WebAssembly.instantiate(await readFile(source), { env: { now: () => performance.now() } });
const e = instance.exports;
if (e.catalogue()) throw Error('Rust catalogue metadata failed');
const catalogue = JSON.parse(new TextDecoder().decode(new Uint8Array(e.memory.buffer, e.metadata_ptr(), e.metadata_len())));
function stripNull(v) {
  if (typeof v !== 'object' || v === null) return v;
  return Object.fromEntries(Object.entries(v).filter(([, x]) => x !== null).map(([k, x]) => [k, stripNull(x)]));
}
const generated = new URL('src/browser/presets.generated.ts', root);
// The family's type is the catalogue's (parameters.generated.ts); only the
// preset values are read out of the binding here.
const content = '// Generated by scripts/build-wasm.mjs from Rust presets. Do not edit.\n' +
  'import type { Family } from "./parameters.generated";\n' +
  'export type { Family };\n' +
  `export const CATALOGUE: { abiId: number; id: string; name: string; note: string; family: Family }[] = ${JSON.stringify(catalogue.map(stripNull), null, 2)};\n`;
// The committed file is held to what the presets render, as parameter_reference.rs
// holds docs/parameters.md: a stale copy fails here rather than being rewritten
// under the tests that read it (fn-216 FRICTION.md). TELPERION_WRITE_REFERENCE=1
// rewrites it.
const committed = await readFile(generated, 'utf8').catch(() => '');
if (process.env.TELPERION_WRITE_REFERENCE) {
  await mkdir(new URL('src/browser/', root), { recursive: true });
  await writeFile(generated, content);
} else if (committed !== content) {
  throw Error('src/browser/presets.generated.ts is not what the Rust presets render; ' +
    'rerun with TELPERION_WRITE_REFERENCE=1 and commit it');
}
// Each binding sits beside its entry point, in the source for the dev server
// and in dist for the package, so `new URL(..., import.meta.url)` finds it at
// run time and a Node caller reads it from the same place. Nothing is inlined
// into the scripts.
await mkdir(new URL('dist/', root), { recursive: true });
// The field entry (src/field) grows on the CPU through the same module
// (fn-353), read from beside itself. It ships without its custom sections
// (function names, producers, target features): nothing reads them at run
// time, and they were 23,682 of its Brotli bytes (fn-366, lever a).
const shipped = strip(await readFile(source));
for (const dir of ['src/browser/', 'src/field/', 'dist/']) await writeFile(new URL(`${dir}telperion.wasm`, root), shipped);
console.log(`Built the Wasm; the family metadata was ${process.env.TELPERION_WRITE_REFERENCE ? 'rewritten' : 'current'}.`);

/** The module with every custom section (id 0) left out, the others as built.
 * @param {Uint8Array} bytes */
function strip(bytes) {
  const kept = [bytes.subarray(0, 8)];
  for (let at = 8; at < bytes.length;) {
    const start = at, id = bytes[at++];
    let size = 0;
    for (let shift = 0, b = 0x80; b & 0x80; shift += 7) size += ((b = bytes[at++]) & 0x7f) * 2 ** shift;
    at += size;
    if (id !== 0) kept.push(bytes.subarray(start, at));
  }
  return Buffer.concat(kept);
}
